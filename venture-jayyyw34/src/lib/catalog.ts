export function potToListing(pot: CatalogPot, day: string): Listing {
  return {
    id: `${pot.id}_${day}`,
    cookId: pot.cookId,
    cookName: pot.cookName,
    cookLine: pot.cookLine,
    neighborhood: pot.neighborhood,
    island: pot.island,
    title: pot.title,
    description: pot.description,
    priceCents: pot.priceCents,
    servingsLeft: pot.servingsLeft,
    tags: pot.tags,
    pepper: pot.pepper,
    daypart: pot.daypart,
    visual: pot.visual,
    availableDate: day,
    pickupWindow: pot.pickupWindow,
    seeded: true,
  };
}
